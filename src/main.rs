use anyhow::Result;
use clap::{Parser, Subcommand};

use crate::cli::VTClient;

fn require_auth(auth: &Option<String>) -> Result<String> {
    auth.clone()
        .ok_or_else(|| anyhow::anyhow!("VT_AUTH not set — run `vt init` and export the token"))
}

mod cli;
mod core;
#[cfg(target_os = "macos")]
mod fido2;
#[cfg(target_os = "macos")]
mod fido2_cli;
mod security;
#[cfg(target_os = "macos")]
mod serve;
#[cfg(target_os = "macos")]
mod ssh_agent;
#[cfg(target_os = "macos")]
mod ssh_cli;

#[derive(Parser)]
#[command(
    author,
    version,
    about = "a simple kms. no plain, explicit auth everywhere"
)]
struct Cli {
    #[arg(
        long,
        global = true,
        env = "VT_ADDR",
        hide_env = true,
        help = "Host and port in the format host:port, e.g. 127.0.0.1:5757 (env: VT_ADDR)"
    )]
    addr: Option<String>,

    #[arg(
        long,
        global = true,
        env = "VT_AUTH",
        hide_env = true,
        help = "Authorization token, generated by `vt init` command (env: VT_AUTH)"
    )]
    auth: Option<String>,

    #[command(subcommand)]
    command: Commands,
}

#[derive(Subcommand, PartialEq)]
enum Commands {
    /// Show version information
    Version,
    /// Will read plain text and output encrypted message for you
    Create,
    /// Decrypt an existing vt protocol as plaintext
    Read {
        #[arg(help = "A string in vt protocol format, e.g. vt://mac/0xxxx")]
        vt: String,

        #[arg(long, help = "Reason shown in the bio auth prompt")]
        reason: Option<String>,
    },
    /// Read env/file and decrypt vt protocol, output to output-file or standard output
    Inject {
        #[arg(
            short = 'r',
            long = "replace-file",
            help = "Path to the file to replace with the decrypted vt protocol"
        )]
        replace_file: Option<String>,

        #[arg(short = 'i', long = "input-file", help = "Path to the input file")]
        input_file: Option<String>,

        #[arg(short = 'o', long = "output-file", help = "Path to the output file")]
        output_file: Option<String>,

        #[arg(
            short = 't',
            long,
            default_value = "2",
            help = "Timeout for deleting output_file after the spawned process in seconds"
        )]
        timeout: u32,

        #[arg(long, help = "Reason shown in the bio auth prompt")]
        reason: Option<String>,

        #[arg(
            trailing_var_arg = true,
            help = "Additional arguments to pass to the spawned process"
        )]
        args: Vec<String>,
    },

    /// Trigger bio auth on the vt server (for use with PAM, sudo, etc.)
    Auth {
        #[arg(long, help = "Reason shown in the bio auth prompt")]
        reason: Option<String>,
    },

    #[cfg(target_os = "macos")]
    /// (Mac only) Run vt server
    Serve {
        #[arg(
            long = "enable-http",
            default_value_t = false,
            help = "Enable the HTTP server for encrypt/decrypt endpoints"
        )]
        enable_http: bool,
        #[arg(
            long = "ssh-idle-timeout",
            default_value_t = ssh_agent::DEFAULT_IDLE_TIMEOUT_SECS,
            help = "SSH agent idle timeout in seconds before clearing keys from memory"
        )]
        ssh_idle_timeout: u64,
        #[arg(
            long = "ssh-auth-cache-mode",
            default_value = "none",
            help = "Auth cache mode: none, per-session, or per-app"
        )]
        auth_cache_mode: ssh_agent::AuthCacheMode,
        #[arg(
            long = "ssh-auth-cache-duration",
            default_value_t = ssh_agent::DEFAULT_AUTH_CACHE_DURATION_SECS,
            help = "Auth cache duration in seconds for sign operations"
        )]
        auth_cache_duration: u64,
    },
    /// (Mac only) Initialize passcode, passphrase which will be used by server
    #[cfg(target_os = "macos")]
    Init,
    /// (Mac only) Manage master secret
    #[cfg(target_os = "macos")]
    #[command(subcommand)]
    Secret(SecretCommands),
    /// (Mac only) SSH agent and key management
    #[cfg(target_os = "macos")]
    #[command(subcommand)]
    Ssh(SshCommands),
    /// (Mac only) Manage FIDO2 (YubiKey) credentials for Touch ID fallback
    #[cfg(target_os = "macos")]
    #[command(subcommand)]
    Fido2(Fido2Commands),
}

#[cfg(target_os = "macos")]
#[derive(Subcommand, PartialEq)]
pub enum Fido2Commands {
    /// Register a new YubiKey. Requires Touch ID or password first.
    Register {
        #[arg(short = 'l', long = "label", help = "Human label for this credential")]
        label: Option<String>,
    },
    /// List registered YubiKey credentials
    List,
    /// Remove a credential by short-id prefix
    Remove {
        #[arg(help = "Short-id prefix (shown in `vt fido2 list`)")]
        short_id: String,
    },
    /// Remove all credentials
    RemoveAll,
}

#[cfg(target_os = "macos")]
#[derive(Subcommand, PartialEq)]
pub enum SecretCommands {
    /// Export the encrypted master secret
    Export,
    /// Import an encrypted master secret
    Import,
    /// Rotate the passcode for the master secret
    RotatePasscode {
        #[arg(long, help = "Absolute path to the new vt binary")]
        bin_absolute_path: Option<String>,
    },
}

#[cfg(target_os = "macos")]
#[derive(Subcommand, PartialEq)]
pub enum SshCommands {
    /// Start the SSH agent (listens on ~/.ssh/vt.sock)
    Agent {
        #[arg(
            short = 't',
            long = "timeout",
            default_value_t = ssh_agent::DEFAULT_IDLE_TIMEOUT_SECS,
            help = "Idle timeout in seconds before clearing keys from memory"
        )]
        timeout: u64,
        #[arg(
            long = "ssh-auth-cache-mode",
            default_value = "none",
            help = "Auth cache mode: none, per-session, or per-app"
        )]
        auth_cache_mode: ssh_agent::AuthCacheMode,
        #[arg(
            long = "ssh-auth-cache-duration",
            default_value_t = ssh_agent::DEFAULT_AUTH_CACHE_DURATION_SECS,
            help = "Auth cache duration in seconds for sign operations"
        )]
        auth_cache_duration: u64,
    },
    /// Add an SSH private key to the keychain
    Add {
        #[arg(short = 'f', long = "file", help = "Path to the SSH private key file")]
        file: Option<String>,
        #[arg(
            short = 'c',
            long = "comment",
            help = "Comment for the key (overrides key's embedded comment)"
        )]
        comment: Option<String>,
    },
    /// List stored SSH keys
    List,
    /// Remove an SSH key by fingerprint
    Remove {
        #[arg(help = "Fingerprint (or prefix) of the key to remove")]
        fingerprint: String,
    },
    /// Remove all stored SSH keys
    RemoveAll,
    /// Change the comment of a stored SSH key
    Comment {
        #[arg(help = "Fingerprint (or prefix) of the key to update")]
        fingerprint: String,
        #[arg(short = 'c', long = "comment", help = "New comment for the key")]
        comment: String,
    },
    /// Show the public key for a stored SSH key
    Show {
        #[arg(help = "Fingerprint (or prefix) of the key to show")]
        fingerprint: String,
    },
}

async fn run(cli: Cli) -> Result<()> {
    match &cli.command {
        Commands::Version => {
            println!("vt {}", env!("CARGO_PKG_VERSION"));
            return Ok(());
        }
        #[cfg(target_os = "macos")]
        Commands::Serve { .. } | Commands::Init => match &cli.command {
            Commands::Serve {
                enable_http,
                ssh_idle_timeout,
                auth_cache_mode,
                auth_cache_duration,
            } => {
                serve::serve(
                    cli.addr.as_deref().unwrap_or("127.0.0.1:5757"),
                    *enable_http,
                    *ssh_idle_timeout,
                    *auth_cache_mode,
                    *auth_cache_duration,
                )
                .await
            }
            Commands::Init => cli::init(),
            _ => unreachable!(),
        },
        #[cfg(target_os = "macos")]
        Commands::Secret(secret_command) => match secret_command {
            SecretCommands::Export => cli::export_secret().await,
            SecretCommands::Import => cli::import_secret().await,
            SecretCommands::RotatePasscode { bin_absolute_path } => {
                cli::rotate_passcode(bin_absolute_path.clone()).await
            }
        },
        #[cfg(target_os = "macos")]
        Commands::Ssh(ssh_command) => match ssh_command {
            SshCommands::Agent {
                timeout,
                auth_cache_mode,
                auth_cache_duration,
            } => ssh_agent::start_ssh_agent(*timeout, *auth_cache_mode, *auth_cache_duration).await,
            SshCommands::Add { file, comment } => ssh_cli::ssh_add(file.clone(), comment.clone()),
            SshCommands::List => ssh_cli::ssh_list(),
            SshCommands::Remove { fingerprint } => ssh_cli::ssh_remove(fingerprint),
            SshCommands::RemoveAll => ssh_cli::ssh_remove_all(),
            SshCommands::Comment {
                fingerprint,
                comment,
            } => ssh_cli::ssh_comment(fingerprint, comment),
            SshCommands::Show { fingerprint } => ssh_cli::ssh_show(fingerprint),
        },
        #[cfg(target_os = "macos")]
        Commands::Fido2(cmd) => match cmd {
            Fido2Commands::Register { label } => fido2_cli::fido2_register(label.clone()),
            Fido2Commands::List => fido2_cli::fido2_list(),
            Fido2Commands::Remove { short_id } => fido2_cli::fido2_remove(short_id),
            Fido2Commands::RemoveAll => fido2_cli::fido2_remove_all(),
        },
        Commands::Create => {
            let auth = require_auth(&cli.auth)?;
            let vt_client = VTClient::new(cli.addr.clone(), auth);
            cli::create(vt_client).await
        }
        Commands::Read { vt, reason } => {
            let auth = require_auth(&cli.auth)?;
            let vt_client = VTClient::new(cli.addr.clone(), auth);
            cli::read(vt_client, vt.to_string(), reason.as_deref()).await
        }
        Commands::Auth { reason } => {
            let auth = require_auth(&cli.auth)?;
            let vt_client = VTClient::new(cli.addr.clone(), auth);
            cli::auth(vt_client, reason.as_deref().unwrap_or("bio auth requested")).await
        }
        Commands::Inject {
            replace_file,
            input_file,
            output_file,
            timeout,
            reason,
            args,
        } => {
            let auth = require_auth(&cli.auth)?;
            let vt_client = VTClient::new(cli.addr.clone(), auth);
            cli::inject(
                vt_client,
                replace_file.clone(),
                input_file.clone(),
                output_file.clone(),
                *timeout,
                reason.as_deref(),
                args.clone(),
            )
            .await
        }
    }
}

#[tokio::main]
async fn main() {
    let log_level = std::env::var("RUST_LOG")
        .unwrap_or_else(|_| {
            if cfg!(debug_assertions) {
                "debug".to_string()
            } else {
                "info".to_string()
            }
        })
        .parse::<tracing::Level>()
        .unwrap_or(tracing::Level::INFO);
    tracing_subscriber::fmt()
        .with_max_level(log_level)
        .with_target(true)
        .with_line_number(true)
        .compact()
        .init();
    let cli = Cli::parse();

    if let Err(e) = run(cli).await {
        tracing::error!("Command failed: {:?}", e);
        std::process::exit(1);
    }
}
